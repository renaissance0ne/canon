@dataclass(frozen=True)
class InjectionRates:
    """Default divergence rates. Every injection type has a matching detector.

    The last row matters most. A generator that only produces resolvable
    conflicts makes the system look perfect and the paper look naive —
    ``ambiguous`` cases exist so the system can be scored on whether it
    ESCALATES them rather than guessing.

    Rates are a fraction of ALL generated records, not of accounts alone.
    """

    reparent: float = 0.05
    stale_attribute: float = 0.08
    name_variant: float = 0.12
    missing_record: float = 0.03
    duplicate_record: float = 0.02
    ambiguous: float = 0.02

    def as_mapping(self) -> dict[InjectionKind, float]:
        """Spelled out rather than reflected, so mypy checks the key set."""
        return {
            "reparent": self.reparent,
            "stale_attribute": self.stale_attribute,
            "name_variant": self.name_variant,
            "missing_record": self.missing_record,
            "duplicate_record": self.duplicate_record,
            "ambiguous": self.ambiguous,
        }


@dataclass(frozen=True)
class ManifestEntry:
    """One injected divergence, and the answer it is scored against.

    ``entity_id`` always names the real-world entity, never the artifact of the
    injection: a duplicate is recorded against the record it duplicates, so a
    consumer never has to know which id was minted second. The entity's type is
    carried by its id prefix (``ACC-``, ``USR-``, ``ROL-``, ``TER-``) — the JSON
    shape is fixed by AGENTS.md § Synthetic Data & Ground Truth and this module
    does not get to extend it.
    """

    entity_id: str
    field: str
    true_value: str | None
    side_a_value: str | None
    side_b_value: str | None
    conflict_class: ConflictClass
    #: The correct outcome — which may be the literal string "escalate".
    expected_resolution: str


@dataclass
class Record:
    """One entity, in the shape a source system would hand back.

    Mutable on purpose. Injection works by cloning the canonical record onto
    both sides and then editing exactly one of them, which is a great deal
    easier to read than threading immutable updates through six injection types.

    ``to_raw`` flattens the attributes to top level rather than nesting them,
    because that is what a Salesforce row and a warehouse row both look like.
    The synthetic connector therefore exercises the same ``normalize`` path the
    real ones will, which is the only reason benchmark numbers transfer.
    """

    external_id: str
    entity_type: EntityType
    name: str
    parent_external_id: str | None
    last_modified_at: datetime
    attributes: dict[str, str | None] = field(default_factory=dict)

    def clone(self) -> Record:
        return Record(
            external_id=self.external_id,
            entity_type=self.entity_type,
            name=self.name,
            parent_external_id=self.parent_external_id,
            last_modified_at=self.last_modified_at,
            attributes=dict(self.attributes),
        )

    def to_raw(self) -> dict[str, str | None]:
        """camelCase, flat — the wire shape ``normalize`` consumes."""
        return {
            "externalId": self.external_id,
            "name": self.name,
            "parentExternalId": self.parent_external_id,
            "lastModifiedAt": self.last_modified_at.isoformat(),
            **self.attributes,
        }


@dataclass
class Org:
    """The canonical org — one truth, before it is copied into two views."""

    records: dict[EntityType, list[Record]]

    def flat(self) -> list[Record]:
        """Every record, in a fixed order. Never iterate a set to build this."""
        return [record for entity_type in ENTITY_FILES for record in self.records[entity_type]]


#: One side's records, keyed for O(1) edit and delete. Insertion order is the
#: canonical order, so the files stay diffable between two seeds.
Side = dict[EntityType, dict[str, Record]]


# ── Public entry point ───────────────────────────────────────────────────────


def generate(
    *,
    seed: int,
    accounts: int,
    out_dir: Path,
    rates: InjectionRates | None = None,
    force: bool = False,
) -> list[ManifestEntry]:
    """Write side A, side B and manifest.json into ``out_dir``.

    Seeded so runs are reproducible; commit the seed used for reported results.

    Refuses to write into a directory that already holds a dataset unless
    ``force`` is set. A silently overwritten dataset is one whose reported
    numbers can no longer be reproduced, and the failure is invisible at the
    moment it happens.
    """
    if accounts < 1:
        raise ValueError("accounts must be at least 1")

    rates = rates or InjectionRates()
    rng = random.Random(seed)
    ids = _Ids()

    org = _build_org(rng, ids, accounts=accounts)
    side_a = _copy_side(org)
    side_b = _copy_side(org)

    injector = _Injector(rng=rng, ids=ids, org=org, side_a=side_a, side_b=side_b)
    entries = _inject(rng, injector, org, rates)

    _write_dataset(
        out_dir,
        org=org,
        side_a=side_a,
        side_b=side_b,
        entries=entries,
        seed=seed,
        accounts=accounts,
        rates=rates,
        force=force,
    )
    return entries


def load_manifest(path: Path) -> list[ManifestEntry]:
    """Read a manifest back. ``path`` is the file or the dataset directory.

    Validated rather than trusted: a manifest is the thing every reported number
    is measured against, so a malformed one has to fail here and not turn into a
    silently wrong denominator three modules downstream.
    """
    if path.is_dir():
        path = path / MANIFEST_FILE

    parsed = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(parsed, list):
        raise ValueError(f"{path} is not a manifest — expected a JSON array of entries.")

    return [_entry_from_json(item, source=path) for item in parsed]


# ── Building the canonical org ───────────────────────────────────────────────


class _Ids:
    """Sequential external ids, one counter per prefix.

    Duplicate injection mints ids after the org is built, and they have to look
    native. A duplicate wearing a recognisable id would be found by its id
    rather than by the matcher, and the benchmark would be measuring nothing.
    """

    def __init__(self) -> None:
        self._next: dict[str, int] = {}

    def mint(self, entity_type: EntityType) -> str:
        prefix = _ID_PREFIX[entity_type]
        number = self._next.get(prefix, 0) + 1
        self._next[prefix] = number
        return f"{prefix}-{number:06d}"


def _build_org(rng: random.Random, ids: _Ids, *, accounts: int) -> Org:
    """Roles, then territories, then users, then accounts.

    The order is a dependency order, not a preference: an account's ``ownerId``
    has to name a user that exists, and a user's ``roleName`` has to be a rung
    that exists.
    """
    roles = _build_roles(rng, ids)
    territories = _build_territories(rng, ids, accounts=accounts)
    users = _build_users(rng, ids, accounts=accounts, territories=territories)
    account_records = _build_accounts(
        rng, ids, accounts=accounts, users=users, territories=territories
    )

    return Org(
        records={
            "account": account_records,
            "user": users,
            "role": roles,
            "territory": territories,
        }
    )


def _build_roles(rng: random.Random, ids: _Ids) -> list[Record]:
    """The ladder, as entities. One rung reports to the one above it.

    Deliberately not scaled by ``accounts``: a company with ten thousand
    accounts does not have a hundred rungs, it has the same five and more people
    on each.
    """
    records: list[Record] = []
    previous: str | None = None

    for level, title in enumerate(_ROLE_LADDER):
        external_id = ids.mint("role")
        records.append(
            Record(
                external_id=external_id,
                entity_type="role",
                name=title,
                parent_external_id=previous,
                last_modified_at=_aged(rng),
                attributes={"level": str(level)},
            )
        )
        previous = external_id

    return records


def _build_territories(rng: random.Random, ids: _Ids, *, accounts: int) -> list[Record]:
    """Flat: territories roll up to regions, and the region is an attribute."""
    wanted = max(4, round(accounts * _TERRITORIES_PER_ACCOUNT))
    pairs = [(region, sub) for region in _REGIONS for sub in _SUBREGIONS][:wanted]

    return [
        Record(
            external_id=ids.mint("territory"),
            entity_type="territory",
            name=f"{region}-{sub}",
            parent_external_id=None,
            last_modified_at=_aged(rng),
            attributes={"region": region},
        )
        for region, sub in pairs
    ]


def _build_users(
    rng: random.Random,
    ids: _Ids,
    *,
    accounts: int,
    territories: list[Record],
) -> list[Record]:
    """A management tree. ``roleName`` is read off the depth, never drawn
    independently, so nobody ends up a Sales Manager reporting to an AE."""
    count = max(len(_ROLE_LADDER), round(accounts * _USERS_PER_ACCOUNT))
    external_ids = [ids.mint("user") for _ in range(count)]
    names = _unique_person_names(rng, count)
    parents, depths = _build_tree(rng, external_ids, roots=1, max_depth=len(_ROLE_LADDER) - 1)
    territory_names = [record.name for record in territories]

    return [
        Record(
            external_id=external_id,
            entity_type="user",
            name=names[index],
            parent_external_id=parents[external_id],
            last_modified_at=_aged(rng),
            attributes={
                "roleName": _ROLE_LADDER[depths[external_id]],
                "territory": rng.choice(territory_names),
                "isActive": "true" if rng.random() < 0.92 else "false",
            },
        )
        for index, external_id in enumerate(external_ids)
    ]


def _build_accounts(
    rng: random.Random,
    ids: _Ids,
    *,
    accounts: int,
    users: list[Record],
    territories: list[Record],
) -> list[Record]:
    external_ids = [ids.mint("account") for _ in range(accounts)]
    names = _unique_company_names(rng, accounts)
    roots = max(_MIN_ROOTS, accounts // _ACCOUNTS_PER_ROOT)
    parents, _ = _build_tree(rng, external_ids, roots=roots, max_depth=_MAX_ACCOUNT_DEPTH)

    owner_ids = [record.external_id for record in users]
    territory_names = [record.name for record in territories]

    return [
        Record(
            external_id=external_id,
            entity_type="account",
            name=names[index],
            parent_external_id=parents[external_id],
            last_modified_at=_aged(rng),
            attributes={
                "territory": rng.choice(territory_names),
                "ownerId": rng.choice(owner_ids),
                "segment": rng.choice(_SEGMENTS),
                "industry": rng.choice(_INDUSTRIES),
            },
        )
        for index, external_id in enumerate(external_ids)
    ]


def _build_tree(
    rng: random.Random,
    external_ids: list[str],
    *,
    roots: int,
    max_depth: int,
) -> tuple[dict[str, str | None], dict[str, int]]:
    """Parent map and depth map, shaped by preferential attachment.

    Uniform random parents give a uniform tree, and a uniform tree is not what
    an org chart looks like. Attaching each new node with probability
    proportional to how many children a node already has produces what real
    hierarchies have: a few large subtrees, a long tail of small ones, and the
    occasional deep chain — which is exactly the shape structural detection has
    to cope with.
    """
    parents: dict[str, str | None] = {}
    depths: dict[str, int] = {}

    #: Nodes still shallow enough to adopt, with weights aligned by index.
    attachable: list[str] = []
    weights: list[int] = []
    position: dict[str, int] = {}

    def _offer(external_id: str) -> None:
        if depths[external_id] < max_depth:
            position[external_id] = len(attachable)
            attachable.append(external_id)
            weights.append(_BASE_ATTACH_WEIGHT)

    for index, external_id in enumerate(external_ids):
        if index < roots or not attachable:
            parents[external_id] = None
            depths[external_id] = 0
        else:
            parent = rng.choices(attachable, weights=weights, k=1)[0]
            parents[external_id] = parent
            depths[external_id] = depths[parent] + 1
            weights[position[parent]] += 1
        _offer(external_id)

    return parents, depths


def _aged(rng: random.Random) -> datetime:
    """A plausible last-modified instant, relative to ``AS_OF`` and never to now."""
    return AS_OF - timedelta(
        days=rng.randrange(_MAX_RECORD_AGE_DAYS),
        seconds=rng.randrange(86_400),
    )


# ── Names ────────────────────────────────────────────────────────────────────


def _fold(name: str) -> str:
    """A conservative stand-in for ``normalize.fold_name``.

    Used for ONE thing: guaranteeing that two generated entities never end up
    with names any reasonable folding would collapse. Ground truth cannot be
    ambiguous about which record is which, and two accounts called "Contoso
    Systems Inc." and "Contoso Systems LLC" would make it exactly that.

    This is not the matcher's fold and must never be used as one —
    ``fold_name`` is the single definition matching depends on. The legal-suffix
    list is imported rather than restated so the two cannot drift apart on the
    part that matters here.
    """
    tokens = ["".join(char for char in token if char.isalnum()) for token in name.lower().split()]
    tokens = [token for token in tokens if token]

    while len(tokens) > 1 and tokens[-1] in LEGAL_SUFFIXES:
        tokens.pop()

    return "".join(tokens)


def _unique_company_names(rng: random.Random, count: int) -> list[str]:
    """Distinct after folding, and terminating.

    On collision the name picks up a qualifier and its own index. Indexes are
    unique and survive folding, so the second attempt cannot collide either —
    no retry loop, no chance of spinning when ``count`` outgrows the word lists.
    """
    names: list[str] = []
    taken: set[str] = set()

    for index in range(count):
        base = f"{rng.choice(_ROOTS)} {rng.choice(_TAILS)}"
        legal = rng.choice(_LEGAL_FORMS)
        candidate = f"{base} {legal}".strip()

        if _fold(candidate) in taken:
            qualifier = _QUALIFIERS[index % len(_QUALIFIERS)]
            candidate = f"{base} {qualifier} {index} {legal}".strip()

        taken.add(_fold(candidate))
        names.append(candidate)

    return names


def _unique_person_names(rng: random.Random, count: int) -> list[str]:
    """Same guarantee as company names; a middle initial does the disambiguating
    first, because that is what a real directory does before it resorts to
    numbering people."""
    names: list[str] = []
    taken: set[str] = set()

    for index in range(count):
        first = rng.choice(_FIRST_NAMES)
        last = rng.choice(_LAST_NAMES)
        candidate = f"{first} {last}"

        if _fold(candidate) in taken:
            initial = chr(ord("A") + index % 26)
            candidate = f"{first} {initial}. {last}"

        if _fold(candidate) in taken:
            candidate = f"{first} {last} {index}"

        taken.add(_fold(candidate))
        names.append(candidate)

    return names


def _name_variants(name: str) -> list[str]:
    """Renderings that fold to the SAME normalized form.

    Case, punctuation, whitespace and legal-suffix differences only. Nothing
    here may change a name in a way ``fold_name`` would not undo: an
    abbreviation ("Traders" → "Trdrs") reads like a cosmetic difference and is
    not one — it would fold to something else, be classified as an attribute
    conflict at severity 2, and the manifest would then be asserting something
    false about the correct answer.
    """
    candidates = [
        name.upper(),
        name.lower(),
        name.replace(".", "").replace(",", ""),
        name.replace(" ", "  ", 1),
        _drop_legal_form(name),
        name.replace("Ltd", "Limited") if "Limited" not in name else name,
    ]

    seen: set[str] = set()
    variants: list[str] = []
    for candidate in candidates:
        if candidate != name and candidate not in seen and candidate.strip():
            seen.add(candidate)
            variants.append(candidate)

    return variants


def _drop_legal_form(name: str) -> str:
    tokens = name.split()
    while len(tokens) > 1 and _fold(tokens[-1]) in LEGAL_SUFFIXES:
        tokens.pop()
    return " ".join(tokens)


# ── Injection ────────────────────────────────────────────────────────────────


def _copy_side(org: Org) -> Side:
    return {
        entity_type: {record.external_id: record.clone() for record in records}
        for entity_type, records in org.records.items()
    }


@dataclass
class _Injector:
    """Applies one divergence at a time and reports what it did.

    Every method returns ``None`` when the record it was handed cannot carry
    that kind of divergence, and returns it WITHOUT touching either side. That
    is what lets the caller hand the record to the next injection type instead
    of burning it, and it is also what guarantees the manifest never claims a
    conflict that was not actually written to disk.
    """

    rng: random.Random
    ids: _Ids
    org: Org
    side_a: Side
    side_b: Side
    _children: dict[EntityType, dict[str, list[str]]] = field(init=False)
    _pools: dict[str, list[str]] = field(init=False)

    def __post_init__(self) -> None:
        self._children = {
            entity_type: _children_index(records)
            for entity_type, records in self.org.records.items()
        }
        self._pools = {
            "territory": [record.name for record in self.org.records["territory"]],
            "region": list(_REGIONS),
            "ownerId": [record.external_id for record in self.org.records["user"]],
            "roleName": list(_ROLE_LADDER),
            "segment": list(_SEGMENTS),
            "industry": list(_INDUSTRIES),
            "isActive": ["true", "false"],
        }

    def inject(self, kind: InjectionKind, record: Record) -> ManifestEntry | None:
        match kind:
            case "reparent":
                return self._reparent(record)
            case "stale_attribute":
                return self._stale_attribute(record)
            case "name_variant":
                return self._name_variant(record)
            case "missing_record":
                return self._missing_record(record)
            case "duplicate_record":
                return self._duplicate_record(record)
            case "ambiguous":
                return self._ambiguous(record)

    # ── which view diverges ──────────────────────────────────────────────

    def _pick_sides(self) -> tuple[str, Side, Side]:
        """Returns (label of the diverged side, diverged, intact).

        Chosen per injection, never fixed. If side B were always the wrong one,
        a single ``prefer_source`` rule pointed at A would score perfectly and
        the benchmark would be measuring the generator instead of the system.
        """
        if self.rng.random() < 0.5:
            return "a", self.side_a, self.side_b
        return "b", self.side_b, self.side_a

    def _entry(
        self,
        record: Record,
        *,
        field_name: str,
        true_value: str | None,
        diverged_side: str,
        diverged_value: str | None,
        intact_value: str | None,
        conflict_class: ConflictClass,
        expected_resolution: str,
    ) -> ManifestEntry:
        on_a = diverged_side == "a"
        return ManifestEntry(
            entity_id=record.external_id,
            field=field_name,
            true_value=true_value,
            side_a_value=diverged_value if on_a else intact_value,
            side_b_value=intact_value if on_a else diverged_value,
            conflict_class=conflict_class,
            expected_resolution=expected_resolution,
        )

    # ── the six ──────────────────────────────────────────────────────────

    def _reparent(self, record: Record) -> ManifestEntry | None:
        """The CRM moved an account; the warehouse still has the old parent.

        The canonical parent is the CURRENT one, so the diverged side is the
        stale one — it keeps a previous parent and an older timestamp. That is
        what makes ``most_recent`` the right rule here rather than a guess, and
        it is why the injection edits the timestamp as well as the edge.
        """
        if record.parent_external_id is None:
            return None

        blocked = self._descendants(record) | {record.external_id, record.parent_external_id}
        candidates = [
            other.external_id
            for other in self.org.records[record.entity_type]
            if other.external_id not in blocked
        ]
        if not candidates:
            return None

        previous_parent = self.rng.choice(candidates)
        label, diverged, intact = self._pick_sides()
        fresh, stale = self._stale_pair()

        diverged[record.entity_type][record.external_id].parent_external_id = previous_parent
        diverged[record.entity_type][record.external_id].last_modified_at = stale
        intact[record.entity_type][record.external_id].last_modified_at = fresh

        return self._entry(
            record,
            field_name="parentExternalId",
            true_value=record.parent_external_id,
            diverged_side=label,
            diverged_value=previous_parent,
            intact_value=record.parent_external_id,
            conflict_class="structural",
            expected_resolution=record.parent_external_id,
        )

    def _stale_attribute(self, record: Record) -> ManifestEntry | None:
        """One side never got the update. Ownership fields land at severity 3,
        the rest at severity 2 — both are injected on purpose."""
        fields = [
            name
            for name in _STALEABLE[record.entity_type]
            if record.attributes.get(name) is not None
        ]
        if not fields:
            return None

        field_name = self.rng.choice(fields)
        current = record.attributes[field_name]
        previous = self._other_value(field_name, current)
        if previous is None:
            return None

        label, diverged, intact = self._pick_sides()
        fresh, stale = self._stale_pair()

        diverged[record.entity_type][record.external_id].attributes[field_name] = previous
        diverged[record.entity_type][record.external_id].last_modified_at = stale
        intact[record.entity_type][record.external_id].last_modified_at = fresh

        return self._entry(
            record,
            field_name=field_name,
            true_value=current,
            diverged_side=label,
            diverged_value=previous,
            intact_value=current,
            conflict_class="attribute",
            expected_resolution=str(current),
        )

    def _name_variant(self, record: Record) -> ManifestEntry | None:
        """The same name, spelled differently.

        The recency edit is not decoration. Without it the "correct" name would
        be whichever one the generator happened to call canonical, which is not
        a defensible answer to score against; with it, the canonical spelling is
        also the most recently written one and the ground truth agrees with
        every survivorship rule that could reasonably fire.
        """
        variants = _name_variants(record.name)
        if not variants:
            return None

        variant = self.rng.choice(variants)
        label, diverged, intact = self._pick_sides()
        fresh, stale = self._stale_pair()

        diverged[record.entity_type][record.external_id].name = variant
        diverged[record.entity_type][record.external_id].last_modified_at = stale
        intact[record.entity_type][record.external_id].last_modified_at = fresh

        return self._entry(
            record,
            field_name="name",
            true_value=record.name,
            diverged_side=label,
            diverged_value=variant,
            intact_value=record.name,
            conflict_class="cosmetic",
            expected_resolution=record.name,
        )

    def _missing_record(self, record: Record) -> ManifestEntry | None:
        """Present on one side, absent from the other.

        Children of a deleted parent are left pointing at an id that no longer
        resolves on that side. That is not an oversight — it is what a deleted
        parent actually leaves behind, and ``detect.severity_for_orphan`` already
        distinguishes an orphan with children from one without.
        """
        label, diverged, _ = self._pick_sides()
        del diverged[record.entity_type][record.external_id]

        return self._entry(
            record,
            field_name=RECORD_FIELD,
            true_value=record.external_id,
            diverged_side=label,
            diverged_value=None,
            intact_value=record.external_id,
            conflict_class="orphan",
            expected_resolution=record.external_id,
        )

    def _duplicate_record(self, record: Record) -> ManifestEntry | None:
        """One side holds the same real entity twice.

        The copy gets a natively-shaped id and a spelling variant of the name,
        which is how duplicates arrive in practice — two reps creating the same
        account a week apart. Both halves matter: an identical name would be
        caught by string equality and prove nothing about the matcher.
        """
        variants = _name_variants(record.name)
        if not variants:
            return None

        label, diverged, _ = self._pick_sides()
        copy = record.clone()
        copy.external_id = self.ids.mint(record.entity_type)
        copy.name = self.rng.choice(variants)
        copy.last_modified_at = record.last_modified_at + timedelta(days=self.rng.randrange(1, 30))
        diverged[record.entity_type][copy.external_id] = copy

        return self._entry(
            record,
            field_name=RECORD_FIELD,
            true_value=record.external_id,
            diverged_side=label,
            diverged_value=copy.external_id,
            intact_value=None,
            conflict_class="duplicate",
            expected_resolution=record.external_id,
        )

    def _ambiguous(self, record: Record) -> ManifestEntry | None:
        """Both sides edited the same field on the same day, and neither is right.

        Every deterministic tiebreak is deliberately removed: the timestamps are
        identical so ``most_recent`` cannot decide, and both values are present
        and well-formed so ``most_complete`` cannot either. What remains is a
        judgement call, and the correct behaviour is to escalate it.

        A blanket ``prefer_source`` rule would still "resolve" these. That is
        not a hole in the generator — it is the cost such a rule imposes, and
        escalation precision is the metric that charges for it.
        """
        fields = [
            name
            for name in _AMBIGUOUS_FIELDS[record.entity_type]
            if record.attributes.get(name) is not None
        ]
        if not fields:
            return None

        field_name = self.rng.choice(fields)
        current = record.attributes[field_name]

        first = self._other_value(field_name, current)
        if first is None:
            return None
        second = self._other_value(field_name, current, also_not=first)
        if second is None:
            return None

        edited_at = AS_OF - timedelta(days=self.rng.randrange(_FRESH_EDIT_MAX_DAYS))

        for side, value in ((self.side_a, first), (self.side_b, second)):
            target = side[record.entity_type][record.external_id]
            target.attributes[field_name] = value
            target.last_modified_at = edited_at

        return ManifestEntry(
            entity_id=record.external_id,
            field=field_name,
            #: No value is correct. That is the whole point of this row.
            true_value=None,
            side_a_value=first,
            side_b_value=second,
            conflict_class="attribute",
            expected_resolution=ESCALATE,
        )

    # ── helpers ──────────────────────────────────────────────────────────

    def _descendants(self, record: Record) -> set[str]:
        """Everything below ``record``, so a re-parent cannot build a cycle.

        A cycle is not a drift a real system produces, and one on a single side
        would break rollups in a way no resolution could describe.
        """
        children = self._children[record.entity_type]
        found: set[str] = set()
        queue = list(children.get(record.external_id, ()))

        while queue:
            current = queue.pop()
            if current in found:
                continue
            found.add(current)
            queue.extend(children.get(current, ()))

        return found

    def _other_value(
        self,
        field_name: str,
        current: str | None,
        *,
        also_not: str | None = None,
    ) -> str | None:
        pool = self._pools.get(field_name, [])
        options = [value for value in pool if value not in (current, also_not)]
        return self.rng.choice(options) if options else None

    def _stale_pair(self) -> tuple[datetime, datetime]:
        """(fresh, stale). The gap is wide enough that no recency comparison is
        a coin flip — a one-hour difference would make ``most_recent`` correct by
        luck rather than by evidence."""
        fresh = AS_OF - timedelta(
            days=self.rng.randrange(_FRESH_EDIT_MAX_DAYS),
            seconds=self.rng.randrange(86_400),
        )
        stale = fresh - timedelta(days=self.rng.randrange(_MIN_STALE_GAP_DAYS, _MAX_STALE_GAP_DAYS))
        return fresh, stale


def _children_index(records: list[Record]) -> dict[str, list[str]]:
    index: dict[str, list[str]] = {}
    for record in records:
        if record.parent_external_id is not None:
            index.setdefault(record.parent_external_id, []).append(record.external_id)
    return index


def _inject(
    rng: random.Random,
    injector: _Injector,
    org: Org,
    rates: InjectionRates,
) -> list[ManifestEntry]:
    """Fill each type's quota from one shared pool, consuming each record once.

    One injection per entity, and the pool is shared rather than per-type,
    because two divergences on one record interact: a name variant on a record
    that was also deleted from that side describes a conflict that is not there.
    Ground truth has to be a set of independent facts or it is not ground truth.

    A record that cannot carry the current injection type stays in the pool for
    the next one, so a root account being unable to be re-parented does not cost
    it every other kind of divergence too.
    """
    remaining = org.flat()
    rng.shuffle(remaining)
    population = len(remaining)

    entries: list[ManifestEntry] = []
    quotas = rates.as_mapping()

    for kind in _INJECTION_ORDER:
        quota = round(quotas[kind] * population)
        consumed: list[int] = []

        for index, record in enumerate(remaining):
            if len(consumed) >= quota:
                break
            entry = injector.inject(kind, record)
            if entry is not None:
                entries.append(entry)
                consumed.append(index)

        for index in reversed(consumed):
            remaining.pop(index)

    #: Sorted so two manifests from two seeds diff meaningfully, and so a
    #: reader can find an entity without scanning.
    entries.sort(key=lambda entry: (entry.entity_id, entry.field))
    return entries


# ── Writing and reading ──────────────────────────────────────────────────────


def _write_dataset(
    out_dir: Path,
    *,
    org: Org,
    side_a: Side,
    side_b: Side,
    entries: list[ManifestEntry],
    seed: int,
    accounts: int,
    rates: InjectionRates,
    force: bool,
) -> None:
    if out_dir.exists() and any(out_dir.iterdir()) and not force:
        raise FileExistsError(
            f"{out_dir} already holds a dataset. Reported results cite a seed, so "
            f"overwriting one silently would make those numbers unreproducible. "
            f"Pass --force if that is what you meant, or choose another --out."
        )

    sides: dict[str, Side] = {"a": side_a, "b": side_b}

    for entity_type, filename in ENTITY_FILES.items():
        _write_json(
            out_dir / CANONICAL_DIR / filename,
            [record.to_raw() for record in org.records[entity_type]],
        )
        for label, side in sides.items():
            _write_json(
                out_dir / SIDE_DIRS[label] / filename,
                [record.to_raw() for record in side[entity_type].values()],
            )

    _write_json(out_dir / MANIFEST_FILE, [_entry_to_json(entry) for entry in entries])
    _write_json(
        out_dir / META_FILE,
        {
            "generatorVersion": GENERATOR_VERSION,
            "seed": seed,
            "accounts": accounts,
            "asOf": AS_OF.isoformat(),
            "rates": rates.as_mapping(),
            "counts": {
                "canonical": {
                    entity_type: len(records) for entity_type, records in org.records.items()
                },
                "sideA": {entity_type: len(records) for entity_type, records in side_a.items()},
                "sideB": {entity_type: len(records) for entity_type, records in side_b.items()},
                "manifestEntries": len(entries),
            },
        },
    )


def _write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def _entry_to_json(entry: ManifestEntry) -> dict[str, str | None]:
    """camelCase on disk — the shape AGENTS.md § Synthetic Data specifies."""
    return {
        "entityId": entry.entity_id,
        "field": entry.field,
        "trueValue": entry.true_value,
        "sideAValue": entry.side_a_value,
        "sideBValue": entry.side_b_value,
        "conflictClass": entry.conflict_class,
        "expectedResolution": entry.expected_resolution,
    }


def _entry_from_json(item: object, *, source: Path) -> ManifestEntry:
    if not isinstance(item, dict):
        raise ValueError(f"{source} contains a manifest entry that is not an object.")

    return ManifestEntry(
        entity_id=_require_str(item, "entityId", source),
        field=_require_str(item, "field", source),
        true_value=_optional_str(item, "trueValue", source),
        side_a_value=_optional_str(item, "sideAValue", source),
        side_b_value=_optional_str(item, "sideBValue", source),
        conflict_class=_require_conflict_class(item, source),
        expected_resolution=_require_str(item, "expectedResolution", source),
    )


def _require_str(item: dict[str, object], key: str, source: Path) -> str:
    value = item.get(key)
    if not isinstance(value, str):
        raise ValueError(f"{source}: manifest entry field {key!r} must be a string.")
    return value


def _optional_str(item: dict[str, object], key: str, source: Path) -> str | None:
    value = item.get(key)
    if value is not None and not isinstance(value, str):
        raise ValueError(f"{source}: manifest entry field {key!r} must be a string or null.")
    return value


def _require_conflict_class(item: dict[str, object], source: Path) -> ConflictClass:
    value = _require_str(item, "conflictClass", source)
    allowed = get_args(ConflictClass)
    if value not in allowed:
        raise ValueError(f"{source}: conflictClass {value!r} is not one of {sorted(allowed)}.")
    return cast(ConflictClass, value)


# ── CLI ──────────────────────────────────────────────────────────────────────


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m eval.generate",
        description="Generate a synthetic org, two divergent views, and the ground-truth "
        "manifest. Offline and seeded — no source system is contacted and no credential "
        "is read.",
    )
    parser.add_argument("--seed", type=int, default=42, help="Reproducibility seed.")
    parser.add_argument("--accounts", type=int, default=500, help="Accounts in the org.")
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Output directory. Defaults to ./data/run<seed>.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite a directory that already holds a dataset.",
    )
    args = parser.parse_args(argv)

    seed: int = args.seed
    accounts: int = args.accounts
    out_dir: Path = args.out if args.out is not None else Path(f"./data/run{seed}")

    entries = generate(seed=seed, accounts=accounts, out_dir=out_dir, force=args.force)

    by_class: dict[str, int] = {}
    for entry in entries:
        by_class[entry.conflict_class] = by_class.get(entry.conflict_class, 0) + 1
    escalations = sum(1 for entry in entries if entry.expected_resolution == ESCALATE)

    print(f"seed {seed} · {accounts} accounts → {out_dir}")
    print(f"{len(entries)} injected divergences")
    for conflict_class in sorted(by_class):
        print(f"  {conflict_class:<12} {by_class[conflict_class]}")
    print(f"  {'escalate':<12} {escalations} (expected to be escalated, not resolved)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
