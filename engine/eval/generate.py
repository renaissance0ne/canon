"""Synthetic data and ground truth.

Built in Phase 1, BEFORE the engine — you cannot develop a detector without
knowing what it is supposed to detect.

One seed produces three artifacts:

1. the canonical org — a synthetic company hierarchy with realistic shape, not
   uniform: a few large subtrees, many small ones, some depth-4 chains;
2. side A (the "CRM" view) and side B (the "warehouse" view);
3. the ground-truth manifest — every injected divergence, with the resolution
   that is actually correct.

Usage::

    uv run python -m eval.generate --seed 42 --accounts 500 --out ./data/run42

NOTHING IN THIS MODULE TALKS TO A NETWORK.
There is no Salesforce credential here, no Databricks host, no token, no URL,
and there must never be one. The whole point of the synthetic dataset is that
its ground truth is *known*, which is only true because it was constructed
rather than observed. ``synthetic`` is declared in
``pipeline/credentials.py::CREDENTIAL_SCHEMA`` with auth method ``none`` for
exactly this reason, and ``connectors/factory.py`` is the code that relies on
it: a synthetic source is the one kind ``build_connector`` accepts with
``credentials=None``. The real connectors are Phase 5 and read the credentials
the user connected in the console — see AGENTS.md § Security Rules.

The only input that changes the output is ``seed``. Same seed, same bytes.
"""

